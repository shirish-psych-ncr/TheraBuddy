import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'Early Intervention Tracking App.txt'));
const lines = source.toString('utf8').split(/\r?\n/);
const records = new Map();
for (let i = 0; i < lines.length; i++) {
  const id = lines[i].trim();
  if (!/^[A-Z]{2,5}-\d{2,3}$/.test(id)) continue;
  const following = lines.slice(i + 1).map(s => s.trim()).filter(Boolean);
  const title = following[0], description = following[1];
  if (!title || !description || /^[A-Z]{2,5}-\d{2,3}$/.test(description)) throw new Error(`Malformed source record ${id}`);
  if (records.has(id)) {
    const previous = records.get(id);
    if (previous.title !== title || previous.description !== description) throw new Error(`Conflicting repeated source ID ${id}`);
    previous.lines.push(i + 1);
  } else records.set(id, { id, title, description, lines: [i + 1] });
}
if (!records.size) throw new Error('No source IDs found');
const families = [...new Set([...records.keys()].map(id => id.split('-')[0]))];
const mapping = {
  PUB: ['Public entry', 'M7/M9'], AUTH: ['Identity', 'M1/M2'], ONB: ['Centre onboarding', 'M2/M3'],
  MST: ['Centre workspace', 'M4/M7'], STF: ['Staff lifecycle', 'M3/M9'], CHD: ['Child record', 'M3/M9'],
  CAL: ['Scheduling', 'M4/M9'], ATT: ['Attendance', 'M4/M9'], THR: ['Therapist/session workspace', 'M5'],
  ASM: ['Assessments', 'M6'], INT: ['Reviewed suggestions', 'M6'], ACT: ['Activities', 'M5/M6'],
  EQP: ['Equipment', 'M3/M6'], GOA: ['Goals/progress', 'M5/M6'], COL: ['Collaboration', 'M6/M9'],
  RPT: ['Reports/analytics', 'M6/M9'], CFG: ['Configuration', 'M2/M9'], PLT: ['Platform operations', 'M7/M9'],
  SYS: ['Shared system states', 'M1–M9']
};
const escape = value => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
let out = '# Complete source screen inventory\n\n';
out += 'Generated by `node scripts/map-brief.mjs`; do not edit by hand. Re-run with `--check` to verify coverage.\n\n';
out += `Source SHA-256: ${createHash('sha256').update(source).digest('hex').toUpperCase()}.\n\n`;
out += `${records.size} unique IDs across ${families.length} families; ${[...records.values()].reduce((n,r) => n+r.lines.length,0)} total occurrences. All repeated IDs have matching titles and descriptions.\n\n`;
out += 'All entries are **backlog / not implemented**. Milestone bands are family-level planning, not promises that every feature in a family ships together. The roadmap defines the first slice; advanced capabilities remain deferred. Source line numbers refer to the original text file.\n\n';
out += '| Family | Area | Unique IDs | Milestone band |\n|---|---|---:|---|\n';
for (const family of families) {
  if (!mapping[family]) throw new Error(`Unmapped family ${family}`);
  out += `| ${family} | ${mapping[family][0]} | ${[...records.keys()].filter(id=>id.startsWith(family+'-')).length} | ${mapping[family][1]} |\n`;
}
for (const family of families) {
  out += `\n## ${family} — ${mapping[family][0]}\n\n| ID | Screen/state | Purpose | Source lines |\n|---|---|---|---|\n`;
  for (const r of records.values()) if (r.id.startsWith(family+'-')) out += `| ${r.id} | ${escape(r.title)} | ${escape(r.description)} | ${r.lines.join(', ')} |\n`;
}
const target = path.join(root, 'docs/11-screen-inventory.md');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== out) throw new Error('Inventory differs; regenerate and review');
  console.log(`PASS: ${records.size} unique IDs, ${families.length} families; complete matching inventory.`);
} else {
  fs.writeFileSync(target,out);
  console.log(`Generated ${records.size} unique IDs across ${families.length} families.`);
}
